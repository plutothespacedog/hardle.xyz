"""Builds supabase/setup.sql = schema.sql + both word lists.

Run from hardle_js/ after changing the schema or a word list:
    python3 supabase/build-setup.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent

def words(name):
    text = (root / "src" / name).read_text()
    out = sorted({w.strip().lower() for w in text.splitlines() if w.strip()})
    assert all(len(w) == 5 and w.isalpha() and w.isascii() for w in out), name
    return out

def insert(table, ws):
    return (
        f"insert into public.{table} (word)\n"
        f"select unnest(string_to_array('{','.join(ws)}', ','))\n"
        f"on conflict do nothing;\n"
    )

answers = words("wordle-La.txt")
allowed = sorted(set(words("wordle-Ta.txt")) | set(answers))

sql = (root / "supabase" / "schema.sql").read_text()
sql += "\n-- ---------- Word lists (generated by supabase/build-setup.py) ----------\n\n"
sql += insert("answers", answers) + "\n" + insert("allowed_words", allowed)
(root / "supabase" / "setup.sql").write_text(sql)
print(f"wrote supabase/setup.sql: {len(answers)} answers, {len(allowed)} allowed guesses")
